#!/usr/bin/env python3
"""Import weights into The Jal Pari Language (Mojo-level ML, step 6).

Two input modes, same output:
  1. Text format (works everywhere, no torch needed):
       # tok_emb
       0.12 -0.03 0.5 ...
       # ln1_g
       1.0 1.0 ...
     A line starting with '#' names the next tensor; the following
     lines (until the next '#') are its floats, whitespace-separated.
  2. PyTorch .pt (needs torch on the machine running this script —
     it is NOT installed in the Jal Pari VM, so this branch is
     provided for the user's own machine, not claimed as run here):
       python3 tools/import_torch_weights.py --input model.pt \\
           --output imported_weights.fg
     It loads torch.load(..., map_location="cpu", weights_only=True)
     and treats every tensor in the state dict as one named array.

Output is a Jal Pari file with one function per tensor:
    fn imported_tok_emb() -> [float] { return [0.12, -0.03, ...]; }
Import it from a Jal Pari program and call the functions to get
the weights as ordinary [float] arrays (e.g. feed them into the
GPT layout, or into Linear structs). Floats are written with
repr(), so the round-trip is exact for float32 values that fit
in a double (which all of them do).

Usage:
    python3 tools/import_torch_weights.py --input weights.txt \\
        --output examples/imported_weights.fg
"""

import argparse
import re
import sys


def parse_text(path):
    tensors = []
    name = None
    vals = []
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.strip()
            if not line:
                continue
            if line.startswith("#"):
                if name is not None:
                    tensors.append((name, vals))
                name = line[1:].strip()
                vals = []
            else:
                vals.extend(float(x) for x in line.split())
    if name is not None:
        tensors.append((name, vals))
    if not tensors:
        raise SystemExit(f"{path}: no tensors found (need '# name' lines)")
    return tensors


def parse_pt(path):
    try:
        import torch
    except ImportError as e:
        raise SystemExit(
            "torch is not installed on this machine, so a .pt file "
            "cannot be read here. Install torch, or export the "
            "weights as text first (see the module docstring)."
        ) from e
    obj = torch.load(path, map_location="cpu", weights_only=True)
    if isinstance(obj, dict) and "state_dict" in obj:
        obj = obj["state_dict"]
    if not isinstance(obj, dict):
        raise SystemExit(f"{path}: expected a state dict, got {type(obj)}")
    tensors = []
    for name, tensor in obj.items():
        flat = tensor.detach().cpu().reshape(-1).tolist()
        tensors.append((name, [float(v) for v in flat]))
    return tensors


def jal_name(name):
    # "model.tok_emb.weight" -> "imported_model_tok_emb_weight"
    clean = re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_")
    return "imported_" + clean


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--input", required=True)
    ap.add_argument("--output", required=True)
    args = ap.parse_args()
    if args.input.endswith(".pt"):
        tensors = parse_pt(args.input)
    else:
        tensors = parse_text(args.input)
    lines = [
        "// Generated by tools/import_torch_weights.py — do not edit by hand.",
        "// One function per imported tensor; call them to get [float] arrays.",
    ]
    for name, vals in tensors:
        fn = jal_name(name)
        body = ", ".join(repr(v) for v in vals)
        lines.append(f"fn {fn}() -> [float] {{")
        lines.append(f"    return [{body}];")
        lines.append("}")
        lines.append("")
    with open(args.output, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    for name, vals in tensors:
        print(f"{name}: {len(vals)} values -> {jal_name(name)}")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
