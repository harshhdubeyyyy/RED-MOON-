#!/usr/bin/env python3
"""Rebase a freestanding big32 kernel from the model's flat
64 KB memory to SOC2 RAM at 0x80000000.

The model's DMEM lives at 0x00000000-0x0000FFFF; SOC2 RAM
lives at 0x80000000-0x80100000. Kernel sources spell their
scratch/stack/heap addresses as decimal literals, so this
shifts every decimal literal in [0x8000, 0x10000) by
+0x80000000. Deliberately untouched: MMIO addresses
(0x10000000+, above the range), CSR numbers, ASCII codes,
counts, sizes, and tick periods (all below 0x8000), and
anything inside a // comment.

Usage: rebase_soc2.py [--check] <in.fg> <out.fg>
  --check prints every replacement and writes nothing.
The generated file carries a header comment naming its
source; it is a build artifact of the source kernel, and
the source stays the version of record.
"""
import re
import sys

BASE = 0x80000000
LO, HI = 0x8000, 0x10000


def rebase_line(line):
    """Return (new_line, [(old, new), ...]) for one line."""
    code, sep, comment = line.partition("//")
    found = []

    def shift(m):
        n = int(m.group(0))
        if LO <= n < HI:
            found.append((n, n + BASE))
            return str(n + BASE)
        return m.group(0)

    return (re.sub(r"\b\d+\b", shift, code)
            + (sep + comment if sep else ""), found)


def main():
    args = sys.argv[1:]
    check = "--check" in args
    args = [a for a in args if a != "--check"]
    if len(args) != 2:
        print(__doc__)
        return 2
    src, dst = args
    with open(src, encoding="utf-8") as f:
        lines = f.read().splitlines()
    out, total = [], 0
    for i, line in enumerate(lines, 1):
        new, found = rebase_line(line)
        for old, newv in found:
            print(f"  {src}:{i}: {old} -> {newv}")
            total += 1
        out.append(new)
    print(f"{total} literal(s) shifted by +0x80000000")
    if check:
        return 0
    header = ("// GENERATED by tools/rebase_soc2.py from "
              f"{src} — do not hand-edit; "
              "edit the source and regenerate.\n")
    with open(dst, "w", encoding="utf-8") as f:
        f.write(header + "\n".join(out) + "\n")
    print(f"wrote {dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
