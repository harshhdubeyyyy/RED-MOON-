#!/usr/bin/env python3
"""Forge-on-big32 verification: build each examples/big32/*.fg with
`forge build --target big32`, run it in the big32 Python model AND in
Icarus Verilog simulation, and compare UART output with the x86 Forge
run. Run from ~/workspace/forge-v2:
    python3 tests/run_big32_tests.py [--big32-dir ../big32]
Requires a big32 checkout (default: ../big32) and iverilog.
"""
import argparse
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FORGE = os.path.join(ROOT, "forge.py")
EXAMPLES = os.path.join(ROOT, "examples", "big32")
OUT = os.path.join(EXAMPLES, "out")

EXPECTED = {
    "hello": "hello from Forge on big32\nforge + big32\n",
    "sum": "sum = 55\n",
    "fib": "fib = 55\n",
    "muldiv": "mul = 83810205\ndiv = 14 rem = 2\nneg = -42\nflag = true false\n",
    "loop_call": "total = 14\nlen = 5 xs[2] = 4\n",
    "forge_os": "forge OS on big32\nboot ok\napp_sum = 55\napp_mul = 42\ndone\n",
}

TB_TEMPLATE = """// Generated by tests/run_big32_tests.py -- do not edit.
`timescale 1ns/1ps
module tb_forge;
    reg clk = 0;
    reg rst_n = 0;
    wire halted;
    wire [7:0] uart_tx;
    wire uart_tx_valid;
    big32 dut (.clk(clk), .rst_n(rst_n), .halted(halted),
               .uart_tx(uart_tx), .uart_tx_valid(uart_tx_valid));
    always @(negedge clk) begin
        if (uart_tx_valid) $write("%c", uart_tx);
    end
    always #5 clk = ~clk;
    integer cycles;
    integer i;
    initial begin
        rst_n = 0;
        for (i = 0; i < 65536; i = i + 1) dut.dmem[i] = 8'b0;
        $readmemh("__HEX__", dut.imem);
        #23;
        rst_n = 1;
        cycles = 0;
        while (!halted && cycles < 1000000) begin
            @(posedge clk);
            cycles = cycles + 1;
        end
        $display("\\n[verilog] halted=%0d cycles=%0d a0=%0d", halted, cycles, dut.core.regs[10]);
        $finish;
    end
endmodule
"""


def run(cmd, cwd=None):
    return subprocess.run(cmd, capture_output=True, text=True, cwd=cwd)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--big32-dir", default=os.path.join(os.path.dirname(ROOT), "big32"))
    args = ap.parse_args()
    big32 = os.path.abspath(args.big32_dir)
    model = os.path.join(big32, "tools", "model.py")
    core = os.path.join(big32, "src", "big32_core.v")
    top = os.path.join(big32, "src", "big32.v")
    for p in (model, core, top):
        if not os.path.exists(p):
            print(f"missing big32 file: {p} (pass --big32-dir)")
            return 1
    os.makedirs(OUT, exist_ok=True)
    failures = []
    for name, expected in sorted(EXPECTED.items()):
        src = os.path.join(EXAMPLES, name + ".fg")
        stem = os.path.join(OUT, name)
        r = run([sys.executable, FORGE, "build", "--target", "big32", src, "-o", stem],
                cwd=ROOT)
        if r.returncode != 0:
            failures.append(f"{name}: build failed: {r.stdout} {r.stderr}")
            continue
        # x86 reference
        rx = run([sys.executable, FORGE, "run", src], cwd=ROOT)
        # Python model
        rm = run([sys.executable, model, stem + ".hex"], cwd=ROOT)
        model_uart = rm.stdout.split("uart:\n", 1)[1] if "uart:\n" in rm.stdout else ""
        # Verilog
        tb_path = os.path.join(OUT, "tb_forge.v")
        with open(tb_path, "w") as f:
            f.write(TB_TEMPLATE.replace("__HEX__", os.path.abspath(stem + ".hex")))
        vvp = os.path.join(OUT, "tb_forge.vvp")
        rc = run(["iverilog", "-o", vvp, core, top, tb_path], cwd=ROOT)
        if rc.returncode != 0:
            failures.append(f"{name}: iverilog failed: {rc.stdout} {rc.stderr}")
            continue
        rv = run(["vvp", vvp], cwd=ROOT)
        verilog_uart, verilog_tail = "", ""
        if "[verilog]" in rv.stdout:
            verilog_uart, verilog_tail = rv.stdout.split("[verilog]", 1)
        # Icarus prints a harmless $readmemh warning for every program
        # whose .hex is shorter than the 4096-word IMEM (all of them,
        # including big32's own programs) -- drop it, and the blank
        # line the $display adds, before comparing UART text.
        verilog_uart = "".join(
            l for l in verilog_uart.splitlines(keepends=True)
            if not l.startswith("WARNING:")).rstrip("\n") + "\n"
        # Verilog cycles are model steps + 1 for every program: this
        # testbench counts the clock edge on which halted is sampled,
        # the model counts executed instructions. Consistent, not a
        # CPU disagreement; UART and a0 are the cross-check.
        model_line = [l for l in rm.stdout.splitlines() if l.startswith("halted=")]
        ok = (rx.stdout == expected and model_uart == expected
              and verilog_uart == expected and rm.returncode == 0)
        status = "PASS" if ok else "FAIL"
        print(f"{status}: {name} | x86 ok={rx.stdout == expected} | "
              f"model: {model_line[0] if model_line else rm.stdout!r} | "
              f"verilog: {verilog_tail.strip()}")
        if not ok:
            failures.append(f"{name}: x86={rx.stdout!r} model={model_uart!r} "
                            f"verilog={verilog_uart!r} expected={expected!r}")
    if failures:
        print(f"FAIL: {len(failures)} failure(s)")
        for f in failures:
            print(" -", f)
        return 1
    print("PASS: all Forge-on-big32 programs match in model and Verilog")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
